int main(int argc, char** argv) {
  std::setvbuf(stdout, nullptr, _IONBF, 0);  // messages before an abort
  if (argc < 2) {
    std::printf("usage: %s EXE\n", argv[0]);
    return 2;
  }
  if (!g_mem.Reserve()) return 1;
  recomp::g_guest_base = g_mem.base();
  // The image: memcpy's jump tables are in it.
  recomp::PeImage exe;
  recomp::g_exe = &exe;
  std::string err;
  if (!exe.Load(argv[1], g_mem, &err)) {
    std::printf("%s: %s\n", argv[1], err.c_str());
    return 1;
  }
  g_mem.Commit(kData, kDataSize, recomp::Prot::RW);
  g_mem.Commit(kStack, kStackSize, recomp::Prot::RW);
  g_mem.Commit(kTeb, 0x1000, recomp::Prot::RW);
  g_mem.write<uint32_t>(kTeb, 0xFFFFFFFF);  // the end of the SEH chain
  recomp::native::msvc_crt::oracle::Setup(g_mem);
  Vc6LocaleFunctions();
  Strings();
  Memory();
  WideStrings();
  Integers();
  AllocaProbe();
  Ftol();
  FloorCeil();
  Intrinsics();
  Output(false);
  Output(true);
  // Every bound function, prefixed as the manifest names it.
  for (uint32_t i = 0; i < kNativeCount; i++)
    if (!g_checked.count(kNatives[i].name)) {
      std::printf("no oracle for msvc_crt::%s (%08X)\n", kNatives[i].name, kNatives[i].va);
      g_failures++;
    }
  std::printf("%ld calls: %ld mismatched\n", g_calls, g_failures);
  return g_failures ? 1 : 0;
}
