recomp::GuestMemory g_mem;
std::mt19937 g_rng(20261107);

// Data at kData (the strings and buffers), the stack below kStackTop.
constexpr uint32_t kData = 0x2F000000, kDataSize = 0x4000;
constexpr uint32_t kStack = 0x2FE00000, kStackSize = 0x100000, kStackTop = kStack + kStackSize;
// The part of the stack a call can write: frames start in the top 4.3 KiB
// and _alloca_probe moves ESP down by at most 256 KiB.
constexpr uint32_t kStackUsed = 0x48000;
// A TEB for the SEH frames some originals set up (fs:[0]).
constexpr uint32_t kTeb = 0x2E300000;

uint32_t Rand(uint32_t n) { return uint32_t(g_rng() % n); }

struct Result {
  Ctx c;
  std::vector<uint8_t> data, stack;
};

enum Regs : unsigned { kEdx = 1, kEcx = 2, kFpu = 4 };

long g_calls = 0, g_failures = 0;
std::map<std::string, long> g_checked;  // calls per bound function

const Native* Find(const std::string& name) {
  for (uint32_t i = 0; i < kNativeCount; i++)
    if (kNatives[i].name == name) return &kNatives[i];
  return nullptr;
}
bool Bound(const std::string& name) { return Find(name); }

bool SameFpu(const recomp::x87::State& a, const recomp::x87::State& b) {
  if (a.cw != b.cw || a.sw != b.sw || a.empty != b.empty || a.top != b.top) return false;
  for (int i = 0; i < 8; i++)
    if (!(a.empty >> i & 1) && (a.r[i].sig != b.r[i].sig || a.r[i].se != b.r[i].se)) return false;
  return true;
}

Result Run(recomp::GuestFn f, const Ctx& c0) {
  Result r;
  r.c = c0;
  f(r.c);
  r.data.assign(g_mem.ptr(kData), g_mem.ptr(kData) + kDataSize);
  r.stack.assign(g_mem.ptr(r.c.esp), g_mem.ptr(kStackTop));
  return r;
}

// Runs every bound copy of `name` (an EXE may hold several, e.g. memcpy
// and memmove from one source) lifted and natively from the guest memory
// and registers as they are now (arguments already on the stack at
// c0.esp).
void Check(const std::string& name, const Ctx& c0, unsigned regs, const std::string& what) {
  for (uint32_t i = 0; i < kNativeCount; i++) {
    const Native& f = kNatives[i];
    if (f.name != name) continue;
    std::vector<uint8_t> data(g_mem.ptr(kData), g_mem.ptr(kData) + kDataSize);
    std::vector<uint8_t> stack(g_mem.ptr(kStackTop - kStackUsed), g_mem.ptr(kStackTop));
    Result a = Run(f.original, c0);
    std::memcpy(g_mem.ptr(kData), data.data(), kDataSize);
    std::memcpy(g_mem.ptr(kStackTop - kStackUsed), stack.data(), kStackUsed);
    Result b = Run(f.native, c0);
    g_calls++;
    g_checked[name]++;
    const Ctx &x = a.c, &y = b.c;
    bool ok = x.eax == y.eax && x.esp == y.esp && x.ebx == y.ebx && x.esi == y.esi &&
              x.edi == y.edi && x.ebp == y.ebp && a.data == b.data && a.stack == b.stack;
    if (regs & kEdx) ok &= x.edx == y.edx;
    if (regs & kEcx) ok &= x.ecx == y.ecx;
    if (regs & kFpu) ok &= SameFpu(x.fpu, y.fpu);
    if (!ok && g_failures++ < 30) {
      std::string data = "same";
      for (uint32_t k = 0; k < kDataSize; k++)
        if (a.data[k] != b.data[k]) {
          char m[48];
          std::snprintf(m, sizeof m, "differs at %08X (%02X/%02X)", kData + k, a.data[k], b.data[k]);
          data = m;
          break;
        }
      std::printf(
          "%s %08X (%s): eax %08X/%08X edx %08X/%08X ecx %08X/%08X esp %08X/%08X data %s stack "
          "%s\n",
          name.c_str(), f.va, what.c_str(), x.eax, y.eax, x.edx, y.edx, x.ecx, y.ecx, x.esp, y.esp,
          data.c_str(), a.stack == b.stack ? "same" : "differs");
    }
  }
}

// Random registers, the return address and the arguments on the stack.
Ctx Frame(std::initializer_list<uint32_t> args) {
  Ctx c{};
  c.eax = g_rng(), c.ecx = g_rng(), c.edx = g_rng(), c.ebx = g_rng();
  c.ebp = g_rng(), c.esi = g_rng(), c.edi = g_rng();
  c.esp = kStackTop - 0x1000 - 4 * Rand(64);
  c.fs_base = kTeb;
  recomp::x87::Init(c.fpu);
  uint32_t p = c.esp;
  g_mem.write<uint32_t>(p, 0xDEAD0000);
  for (uint32_t v : args) g_mem.write<uint32_t>(p += 4, v);
  return c;
}

// The data area: random bytes from a small alphabet, NULs among them.
const uint8_t kAlphabet[] = {0, 'a', 'b', 'c', 'A', 'B', 'Z', '/', 0x7F, 0x80, 0xC4, 0xFF};
uint8_t RandByte() { return kAlphabet[Rand(sizeof kAlphabet)]; }

void FillData() {
  for (uint32_t i = 0; i < kDataSize; i++) g_mem.write<uint8_t>(kData + i, RandByte());
}

// A NUL-terminated string of `len` bytes (no NUL inside) at a random
// offset in [lo, hi) of the data area; returns its address.
uint32_t PutString(uint32_t len, uint32_t lo, uint32_t hi) {
  const uint32_t at = kData + lo + Rand(hi - lo - len - 8);
  for (uint32_t i = 0; i < len; i++) {
    uint8_t b;
    do b = RandByte();
    while (!b);
    g_mem.write<uint8_t>(at + i, b);
  }
  g_mem.write<uint8_t>(at + len, 0);
  return at;
}
uint32_t PutWString(uint32_t len, uint32_t lo, uint32_t hi) {
  const uint32_t at = (kData + lo + Rand(hi - lo - 2 * len - 8)) & ~1u;
  static const uint16_t units[] = {'a', 'b', 'A', 0x80, 0xC4, 0x100, 0xD800, 0xFFFF};
  for (uint32_t i = 0; i < len; i++) g_mem.write<uint16_t>(at + 2 * i, units[Rand(8)]);
  g_mem.write<uint16_t>(at + 2 * len, 0);
  return at;
}
uint32_t Len() { return Rand(8) ? Rand(24) : Rand(400); }
uint32_t SmallChar() {
  // The character argument with random upper bits, which the originals ignore.
  return (g_rng() & 0xFFFFFF00) | RandByte();
}

void Strings() {
  for (int i = 0; i < 20000; i++) {
    FillData();
    // Two strings in disjoint halves (dst in the first, with room after it).
    const uint32_t a = PutString(Len(), 0, 0x1800), b = PutString(Len(), 0x2000, 0x4000);
    const uint32_t a2 = Rand(4) ? PutString(Len(), 0x1800, 0x2000) : b;
    const uint32_t n = Rand(4) ? Rand(32) : Rand(600);
    const uint32_t ch = SmallChar();
    const std::string w = std::to_string(i);
    Check("strlen", Frame({a}), 0, w);
    Check("strcpy", Frame({a, b}), 0, w);
    Check("strcat", Frame({a, b}), 0, w);
    Check("strncpy", Frame({a, b, n}), 0, w);
    Check("strncat", Frame({a, b, n}), 0, w);
    Check("strcmp", Frame({a, a2}), 0, w);
    Check("strcmp", Frame({a, a}), 0, w);
    Check("strncmp", Frame({a, a2, n}), 0, w);
    Check("strchr", Frame({a, ch}), 0, w);
    Check("strchr", Frame({a, ch & 0xFFFFFF00}), 0, w);
    Check("strrchr", Frame({a, ch}), 0, w);
    Check("strstr", Frame({a, PutString(Rand(4), 0x3000, 0x4000)}), 0, w);
    Check("strstr", Frame({a, a + Rand(4)}), 0, w);
    Check("strcspn", Frame({a, PutString(Rand(5), 0x3000, 0x4000)}), 0, w);
    Check("strpbrk", Frame({a, PutString(Rand(5), 0x3000, 0x4000)}), 0, w);
  }
}

void Memory() {
  for (int i = 0; i < 20000; i++) {
    FillData();
    const uint32_t n = Rand(4) ? Rand(80) : Rand(0x1000);
    const uint32_t d = kData + Rand(0x1800), src = kData + Rand(0x2000);  // may overlap
    const std::string w = std::to_string(i);
    Check("memset", Frame({d, SmallChar(), n}), 0, w);
    Check("memcpy", Frame({d, src, n}), 0, w);
    Check("memmove", Frame({d, src, n}), 0, w);
    Check("memchr", Frame({src, SmallChar(), n}), 0, w);
  }
}

void WideStrings() {
  for (int i = 0; i < 20000; i++) {
    FillData();
    const uint32_t a = PutWString(Len() / 2, 0, 0x1800), b = PutWString(Len() / 2, 0x2000, 0x4000);
    const uint32_t n = Rand(4) ? Rand(32) : Rand(300);
    const uint32_t ch = (g_rng() & 0xFFFF0000) | g_mem.read<uint16_t>(a + 2 * Rand(4));
    const std::string w = std::to_string(i);
    Check("wcslen", Frame({a}), 0, w);
    Check("wcscpy", Frame({a, b}), 0, w);
    Check("wcsncpy", Frame({a, b, n}), 0, w);
    Check("wcschr", Frame({a, ch}), 0, w);
    Check("wcschr", Frame({a, ch & 0xFFFF0000}), 0, w);
    Check("wcsrchr", Frame({a, ch}), 0, w);
    Check("wcscspn", Frame({a, PutWString(Rand(4), 0x3000, 0x4000)}), 0, w);
  }
}

uint64_t Rand64() {
  // Mostly values whose halves are 0, small or all ones, where the
  // helpers take their shortcuts.
  auto half = [] {
    switch (Rand(4)) {
      case 0: return 0u;
      case 1: return Rand(16);
      case 2: return 0xFFFFFFFFu - Rand(16);
      default: return uint32_t(g_rng());
    }
  };
  return uint64_t(half()) << 32 | half();
}

void Integers() {
  for (int i = 0; i < 1000000; i++) {
    const uint64_t a = Rand64(), b = Rand64();
    const std::string w = std::to_string(i);
    auto args = [](uint64_t x, uint64_t y) {
      return Frame({uint32_t(x), uint32_t(x >> 32), uint32_t(y), uint32_t(y >> 32)});
    };
    Check("_allmul", args(a, b), kEdx, w);
    if (b) {
      Check("_aulldiv", args(a, b), kEdx, w);
      Check("_aullrem", args(a, b), kEdx, w);
    }
    Ctx c = Frame({});
    c.eax = uint32_t(a), c.edx = uint32_t(a >> 32);
    c.ecx = (g_rng() & 0xFFFFFF00) | (Rand(2) ? Rand(80) : Rand(256));
    Check("_allshl", c, kEdx, w);
  }
}

void AllocaProbe() {
  for (int i = 0; i < 20000; i++) {
    Ctx c = Frame({});
    c.eax = Rand(4) ? Rand(0x100) * 4 : Rand(0x40000) & ~3u;
    Check("_alloca_probe", c, kEcx, std::to_string(c.eax));
  }
}

// _ftol: ST0 from every class and range, under every rounding and
// precision mode, with random state below it on the stack.
recomp::x87::F80 RandF80() {
  using recomp::x87::F80;
  const uint16_t sign = Rand(2) ? 0x8000 : 0;
  switch (Rand(6)) {
    case 0: return {0, uint16_t(sign)};                                     // zero
    case 1: return {0x8000000000000000ull, uint16_t(sign | 0x7FFF)};        // infinity
    case 2: return {0xC000000000000000ull | g_rng(), uint16_t(sign | 0x7FFF)};  // NaN
    case 3: return {uint64_t(g_rng()) << 32 | g_rng(), uint16_t(sign)};     // denormal
    default: {
      // Normal, mostly around the 64-bit integer range.
      const uint16_t e = uint16_t(0x3FFF + (Rand(4) ? int(Rand(70)) - 4 : int(Rand(0x7FFE)) - 0x3FFF));
      return {0x8000000000000000ull | uint64_t(g_rng()) << 32 | g_rng(), uint16_t(sign | e)};
    }
  }
}

void Ftol() {
  for (int i = 0; i < 1000000; i++) {
    Ctx c = Frame({});
    for (int k = Rand(4); k > 0; k--) recomp::x87::LoadF80(c.fpu, RandF80());
    recomp::x87::LoadF80(c.fpu, RandF80());
    // Every precision and rounding control, exceptions masked (as programs
    // run) and some sticky flags already set.
    recomp::x87::SetControlWord(c.fpu, uint16_t(0x003F | Rand(4) << 8 | Rand(4) << 10));
    c.fpu.sw |= uint16_t(Rand(0x40) & 0x3D);
    Check("_ftol", c, kEdx | kFpu, std::to_string(i));
  }
}

// floor/ceil: a double argument of every class (mostly integers, values
// with a fraction around them and denormals), under every rounding and
// precision mode, with 0 to 8 values already on the stack. Exceptions
// stay masked: with one unmasked the native function hands the call to
// the original, which raises it (RaiseException, not served here).
uint64_t RandF64() {
  const uint64_t sign = uint64_t(Rand(2)) << 63;
  switch (Rand(8)) {
    case 0: return sign;                                                    // zero
    case 1: return sign | 0x7FF0000000000000ull;                            // infinity
    case 2: return sign | 0x7FF0000000000000ull | (uint64_t(g_rng()) << 20 | g_rng()) | (Rand(2) ? 1ull << 51 : 1);  // NaN
    case 3: return sign | (uint64_t(g_rng() & 0xFFFFF) << 32 | g_rng());    // denormal
    default: {
      // Around 2^-2..2^60: fractions, integers and the edge at 2^52.
      const uint64_t e = 1021 + Rand(62);
      uint64_t frac = uint64_t(g_rng() & 0xFFFFF) << 32 | g_rng();
      if (!Rand(3)) frac &= ~((1ull << std::min<uint64_t>(52, e > 1075 ? 0 : 1075 - e)) - 1);  // an integer
      return sign | e << 52 | frac;
    }
  }
}

void FloorCeil() {
  for (int i = 0; i < 400000; i++) {
    const uint64_t x = RandF64();
    for (const char* name : {"vc6::floor", "vc6::ceil"}) {
      Ctx c = Frame({uint32_t(x), uint32_t(x >> 32)});
      for (int k = Rand(4) ? Rand(4) : Rand(9); k > 0; k--) recomp::x87::LoadF80(c.fpu, RandF80());
      recomp::x87::SetControlWord(c.fpu, uint16_t(0x7F | Rand(4) << 8 | Rand(4) << 10));
      c.fpu.sw |= uint16_t(Rand(0x40) & 0x3D);
      Check(name, c, kFpu, std::to_string(i));
    }
  }
}

// _CIpow/_CIfmod: x and y of every class, as doubles or as 80-bit values
// (x87 code passes those), for pow mostly a positive x or an integer y,
// and around the exponents where a double result overflows or
// underflows. Every rounding and precision mode, 0x27F itself, 0 to 6
// values already on the stack, and every setting of VC6's switches
// (SetMath). Exceptions stay masked, as for floor/ceil.
recomp::x87::F80 RandOperand(bool pow, bool is_y) {
  const auto f64 = [](uint64_t v) {
    recomp::x87::State t;
    recomp::x87::Init(t);
    recomp::x87::LoadF64(t, v);
    return recomp::x87::StoreF80(t);
  };
  const auto value = [&](double d) {
    uint64_t v;
    std::memcpy(&v, &d, 8);
    return f64(v);
  };
  switch (Rand(pow ? 6 : 3)) {
    case 0: return RandF80();
    case 1:
    case 2: return f64(RandF64());
    case 3:  // an integer, or half of one
      return value((int(Rand(81)) - 40) / (is_y && Rand(4) ? 1.0 : 2.0));
    case 4:  // around overflow and underflow
      return is_y ? value((Rand(2) ? 1 : -1) * (900.0 + Rand(400000) / 100.0))
                  : value((Rand(2) ? 1 : -1) * (1.0 + Rand(1000) / 100.0));
    default: return value(Rand(2) ? 2.0 : 10.0);
  }
}

void Intrinsics() {
  const auto& m = recomp::native::msvc_crt::vc6::GetMath();
  if (!m.matherr_flag) {
    if (Bound("vc6::_CIpow") || Bound("vc6::_CIfmod"))
      std::printf("_CIpow/_CIfmod are bound but Setup() gave no SetMath\n"), g_failures++;
    return;
  }
  for (int i = 0; i < 300000; i++) {
    for (const char* name : {"vc6::_CIpow", "vc6::_CIfmod"}) {
      const bool pow = name[6] == 'p';
      g_mem.write<uint32_t>(m.fastflag, Rand(4) ? 0 : 1);
      g_mem.write<uint32_t>(m.adjust_fdiv, Rand(16) ? 0 : 1);
      g_mem.write<uint32_t>(m.matherr_flag, Rand(4) ? 9876 : 0);
      Ctx c = Frame({});
      for (int k = Rand(4) ? Rand(3) : Rand(7); k > 0; k--) recomp::x87::LoadF80(c.fpu, RandF80());
      recomp::x87::LoadF80(c.fpu, RandOperand(pow, false));
      recomp::x87::LoadF80(c.fpu, RandOperand(pow, true));
      recomp::x87::SetControlWord(
          c.fpu, Rand(4) ? 0x27F : uint16_t(0x7F | Rand(4) << 8 | Rand(4) << 10 | Rand(2) << 12));
      c.fpu.sw |= uint16_t(Rand(0x40) & 0x3D);
      Check(name, c, kFpu, std::to_string(i));
    }
  }
}

// The VC6 locale: the C locale as the image starts, or a code page locale
// as setlocale(LC_CTYPE, ".1252") leaves it, with or without a multibyte
// __mb_cur_max.
constexpr uint32_t kTable = 0x2E200400;  // the code page's ctype table, from index -1
uint32_t g_c_pctype = 0;

enum class Locale { C, CodePage, Multibyte };

void SetLocale(Locale l) {
  const auto& a = recomp::native::msvc_crt::vc6::GetLocale();
  g_mem.write<uint32_t>(a.ctype_handle, l == Locale::C ? 0 : 0x0409);
  g_mem.write<uint32_t>(a.codepage, l == Locale::C ? 0 : 1252);
  g_mem.write<uint32_t>(a.mb_cur_max, l == Locale::Multibyte ? 2 : 1);
  g_mem.write<uint32_t>(a.pctype, l == Locale::C ? g_c_pctype : kTable + 2);
}

const char* LocaleName(Locale l) {
  return l == Locale::C ? "C" : l == Locale::CodePage ? "cp1252" : "mb";
}

// Strings of letters in both cases with other ASCII, and in a quarter of
// them Latin-1 letters and other bytes over 0x7F.
uint32_t PutText(uint32_t len, uint32_t lo, uint32_t hi, bool high) {
  static const uint8_t ascii[] = {'a', 'b', 'z', 'A', 'B', 'Z', '@', '[', '`', '{', '_', '1', ' '};
  static const uint8_t latin[] = {0xC4, 0xE4, 0xD7, 0xF7, 0xDF, 0xFF, 0x80, 0xA0, 0x8A, 0x9A, 0x9F};
  const uint32_t at = kData + lo + Rand(hi - lo - len - 8);
  for (uint32_t i = 0; i < len; i++)
    g_mem.write<uint8_t>(at + i, high && !Rand(6) ? latin[Rand(sizeof latin)] : ascii[Rand(sizeof ascii)]);
  g_mem.write<uint8_t>(at + len, 0);
  return at;
}
// b as a with some bytes' case flipped, and now and then one changed or
// the string cut short.
uint32_t PutVariant(uint32_t a, uint32_t lo, uint32_t hi, bool high) {
  uint32_t len = 0;
  while (g_mem.read<uint8_t>(a + len)) len++;
  const uint32_t b = PutText(len, lo, hi, high);
  for (uint32_t i = 0; i < len; i++) {
    uint8_t ch = g_mem.read<uint8_t>(a + i);
    if (Rand(3) == 0 && ((ch | 0x20) >= 'a' && (ch | 0x20) <= 'z')) ch ^= 0x20;
    if (Rand(3) == 0 && ch >= 0xC0 && ch != 0xD7 && ch != 0xF7) ch ^= 0x20;
    g_mem.write<uint8_t>(b + i, ch);
  }
  if (len && !Rand(3)) g_mem.write<uint8_t>(b + Rand(len), "aZ{\x80"[Rand(4)]);
  if (len && !Rand(4)) g_mem.write<uint8_t>(b + Rand(len), 0);
  return b;
}

// A number as the parsers meet them: spaces (with 0xA0, a space in code
// page 1252), a sign, a 0x/0X or 0 prefix, then digits and letters of
// some base, mostly within 32 bits but now and then far longer, with a
// byte over 0x7F or other junk among or after them.
uint32_t PutNumber(uint32_t lo, uint32_t hi) {
  static const char* const spaces[] = {"", "", " ", "\t", "  \n", "\xA0", " \x0B\x0C\r"};
  static const char* const signs[] = {"", "", "-", "+", "--", "+-"};
  static const char* const prefixes[] = {"", "", "", "0", "0x", "0X", "0x0", "00"};
  static const uint8_t digits[] = {'0', '1', '7', '8', '9', 'a', 'f', 'g', 'z', 'A', 'F', 'Z',
                                   '0', '1', '5', '9', 0xC4, 0xE4, 0xB2, 0xB9, 0xFF, '@', '[', '`', '{'};
  std::string t = std::string(spaces[Rand(7)]) + signs[Rand(6)] + prefixes[Rand(8)];
  const uint32_t n = Rand(4) ? Rand(12) : Rand(40);
  for (uint32_t i = 0; i < n; i++) t += char(Rand(3) ? "0123456789abcdefABCDEF"[Rand(22)] : digits[Rand(sizeof digits)]);
  if (Rand(2)) t += " x";
  const uint32_t at = kData + lo + Rand(hi - lo - uint32_t(t.size()) - 8);
  for (uint32_t i = 0; i < t.size(); i++) g_mem.write<uint8_t>(at + i, uint8_t(t[i]));
  g_mem.write<uint8_t>(at + uint32_t(t.size()), 0);
  return at;
}

const char* const kVc6LocaleFunctions[] = {
    "vc6::tolower", "vc6::toupper", "vc6::_strcmpi", "vc6::_strnicmp", "vc6::_memicmp",
    "vc6::_strlwr", "vc6::_strupr", "vc6::isalpha", "vc6::isdigit", "vc6::isspace",
    "vc6::isalnum", "vc6::iscntrl", "vc6::_isctype", "vc6::atoi", "vc6::atol",
    "vc6::strtol"};

// The code page's ctype table: the C locale's below 0x80 (the image's),
// Latin-1 classes above. False (a failure counted) if Setup() set no
// locale.
bool LocaleTables(const char* what) {
  if (!recomp::native::msvc_crt::vc6::GetLocale().pctype) {
    std::printf("%s bound, but Setup() set no locale\n", what);
    g_failures++;
    return false;
  }
  if (g_c_pctype) return true;
  g_mem.Commit(kTable & ~0xFFFu, 0x1000, recomp::Prot::RW);
  g_c_pctype = g_mem.read<uint32_t>(recomp::native::msvc_crt::vc6::GetLocale().pctype);
  for (int ch = -1; ch < 256; ch++)
    g_mem.write<uint16_t>(kTable + 2 + 2 * ch,
                          ch < 0x80 ? g_mem.read<uint16_t>(g_c_pctype + 2 * ch)
                                    : recomp::CharType1(uint32_t(ch)));
  return true;
}

void Vc6LocaleFunctions() {
  if (std::none_of(std::begin(kVc6LocaleFunctions), std::end(kVc6LocaleFunctions), Bound)) return;
  if (!LocaleTables("VC6 locale functions")) return;
  for (Locale l : {Locale::C, Locale::CodePage, Locale::Multibyte}) {
    SetLocale(l);
    for (int i = 0; i < 40000; i++) {
      FillData();
      const bool high = !Rand(4);
      const uint32_t a = PutText(Len(), 0, 0x1800, high);
      const uint32_t b = Rand(4) ? PutVariant(a, 0x2000, 0x3800, high) : PutText(Len(), 0x2000, 0x3800, high);
      const uint32_t n = Rand(4) ? Rand(32) : Rand(600);
      const std::string w = std::string(LocaleName(l)) + " " + std::to_string(i);
      Check("vc6::_strcmpi", Frame({a, b}), 0, w);
      Check("vc6::_strnicmp", Frame({a, b, n}), 0, w);
      Check("vc6::_memicmp", Frame({a, b, std::min<uint32_t>(n, 0x800)}), 0, w);
      Check("vc6::_strlwr", Frame({a}), 0, w);
      Check("vc6::_strupr", Frame({a}), 0, w);
      // Characters: every byte, EOF, signed chars, and beyond 255.
      const int32_t ch = Rand(2) ? int32_t(Rand(256)) : int32_t(Rand(700)) - 200;
      Check("vc6::tolower", Frame({uint32_t(ch)}), 0, w);
      Check("vc6::toupper", Frame({uint32_t(ch)}), 0, w);
      // The classes read the table for any int; keep to its neighbourhood.
      const int32_t cc = int32_t(Rand(384)) - 128;
      Check("vc6::isalpha", Frame({uint32_t(cc)}), 0, w);
      Check("vc6::isdigit", Frame({uint32_t(cc)}), 0, w);
      Check("vc6::isspace", Frame({uint32_t(cc)}), 0, w);
      Check("vc6::isalnum", Frame({uint32_t(cc)}), 0, w);
      Check("vc6::iscntrl", Frame({uint32_t(cc)}), 0, w);
      Check("vc6::_isctype", Frame({uint32_t(ch), Rand(2) ? 0xFFFFu : 1u << Rand(16)}), 0, w);
      // The number parsers; strtol's end pointer goes to the data area
      // (compared) or is null.
      const uint32_t num = PutNumber(0x3800, 0x3F00);
      Check("vc6::atoi", Frame({num}), 0, w);
      Check("vc6::atol", Frame({num}), 0, w);
      const uint32_t base = Rand(4) ? "\x00\x0A\x10\x08\x02\x24"[Rand(6)] : uint32_t(int32_t(Rand(43)) - 2);
      Check("vc6::strtol", Frame({num, Rand(3) ? kData + 0x3F00 + 4 * Rand(64) : 0, base}), 0, w);
    }
  }
  SetLocale(Locale::C);
}

// _output and _woutput on string streams, as sprintf, _snprintf,
// _vsnprintf and _vsnwprintf set them up (_IOWRT|_IOSTRG, now and then
// _IOERR already set): formats of literal text (bytes over 0x7F, DBCS
// lead bytes, wide characters and U+FFFF among it) and conversions with every
// flag, width and precision (with `*`), size (h l w I64, a bare I, the
// ignored F L N) and type (with %B, which reprints the last text);
// arguments as each asks (strings and wide strings in the data area or
// null, %Z's counted strings, %n pointers, integers at the edges, doubles
// of every class and decimal values at rounding edges); the stream's
// count from 0, so that output overflows, to all of its area. In the three
// locales (the multibyte one with lead bytes), decimal point '.' or ',';
// the x87 stack and control word as for floor/ceil (floats go through
// fld/fstp).
constexpr uint32_t kFmt = kData + 0x2000, kArgs = kData + 0x2800, kOut = kData + 0x3000,
                   kOutEnd = kData + 0x3E00, kCounts = kData + 0x3E00, kFile = kData + 0x3F00,
                   kWide = kData + 0x1800, kCounted = kData + 0x1F00;

uint64_t RandDecimal() {
  // Values whose digits sit at the rounding edges of a precision.
  static const double kEdges[] = {0.5, 1.5, 2.5, 0.05, 0.15, 0.25, 0.35, 0.45, 9.5, 99.5,
                                  0.995, 9.9999995, 1e15, 1e16, 1e17, 123456789.125, 0.1,
                                  0.3, 1.0 / 3, 2.0 / 3, 1e-5, 9.5e-5, 1e21, 1e22, 1e-300,
                                  1e308, 4.9e-324, 2.2250738585072014e-308, 100, 1e100};
  double d = kEdges[Rand(sizeof kEdges / sizeof *kEdges)];
  if (Rand(2)) d *= std::pow(10.0, int(Rand(13)) - 6);
  if (Rand(2)) d = -d;
  uint64_t v;
  std::memcpy(&v, &d, 8);
  return v;
}

std::u16string Units(const std::string& t) { return std::u16string(t.begin(), t.end()); }

// A code page table with DBCS lead bytes (0x81-0x9F, 0xE0-0xFC) for the
// multibyte locale.
constexpr uint32_t kLeadTable = kTable + 0x400;

void Output(bool wide_engine) {
  const char* const name = wide_engine ? "vc6::_woutput" : "vc6::_output";
  if (!Bound(name)) return;
  if (!LocaleTables(name)) return;
  const auto& loc = recomp::native::msvc_crt::vc6::GetLocale();
  for (int ch = -1; ch < 256; ch++)
    g_mem.write<uint16_t>(kLeadTable + 2 + 2 * ch,
                          uint16_t(g_mem.read<uint16_t>(kTable + 2 + 2 * ch) |
                                   ((ch >= 0x81 && ch <= 0x9F) || (ch >= 0xE0 && ch <= 0xFC) ? 0x8000 : 0)));
  for (Locale l : {Locale::C, Locale::CodePage, Locale::Multibyte}) {
    SetLocale(l);
    if (l == Locale::Multibyte) g_mem.write<uint32_t>(loc.pctype, kLeadTable + 2);
    for (int i = 0; i < 100000; i++) {
      FillData();
      g_mem.write<uint8_t>(loc.decimal_point, Rand(4) ? '.' : ',');
      // Strings for %s, wide ones for %S and %ls, counted ones for %Z.
      uint32_t strings[4], wides[4], counted[4];
      for (uint32_t& s : strings) s = PutText(Rand(4) ? Rand(12) : Rand(40), 0, 0x1800, true);
      for (int k = 0; k < 4; k++) {
        const uint32_t at = kWide + 0x180 * k, n = Rand(12);
        for (uint32_t j = 0; j < n; j++)
          g_mem.write<uint16_t>(at + 2 * j, Rand(4) ? uint16_t("aZ 1."[Rand(5)]) : uint16_t(Rand(4) ? Rand(0x100) : Rand(0x10000)));
        g_mem.write<uint16_t>(at + 2 * n, 0);
        wides[k] = at;
        const uint32_t z = kCounted + 0x10 * k;
        g_mem.write<uint16_t>(z, uint16_t(Rand(4) ? Rand(24) : Rand(0x400)));
        g_mem.write<uint32_t>(z + 4, Rand(6) ? (Rand(2) ? strings[k] : at) : 0);
        counted[k] = z;
      }
      // Every argument slot a readable string by default, then the
      // conversions' own.
      for (uint32_t a = kArgs; a < kOut; a += 4) g_mem.write<uint32_t>(a, strings[Rand(4)]);
      std::u16string fmt;  // units of the engine's width
      uint32_t ap = kArgs;
      auto push = [&](uint32_t v) {
        if (ap < kOut) g_mem.write<uint32_t>(ap, v);
        ap += 4;
      };
      auto edge = [&] {
        static const uint32_t k[] = {0, 1, 7, 9, 10, 0x7F, 0x80, 0xFF, 0x8000, 0xFFFF,
                                     0x7FFFFFFF, 0x80000000, 0xFFFFFFFF, 1000000};
        return Rand(3) ? k[Rand(sizeof k / sizeof *k)] : uint32_t(g_rng()) >> Rand(32);
      };
      const int pieces = 1 + int(Rand(8));
      for (int p = 0; p < pieces && fmt.size() < 0x380; p++) {
        if (Rand(3) == 0) {  // literal text
          static const char16_t kNarrow[] = u"ab Z.\x80\xC4\xA0\x7F\x81";
          static const char16_t kWideText[] = u"ab Z.\x80\xC4\x20AC\x4E2D\xFFFF";
          for (int n = int(Rand(8)); n > 0; n--) {
            fmt += wide_engine ? kWideText[Rand(10)] : kNarrow[Rand(10)];
            if (fmt.back() == 0x81) fmt += u'a';  // a lead byte's trail, not a '%'
          }
          continue;
        }
        if (!Rand(16)) {
          fmt += u"%%";
          continue;
        }
        fmt += '%';
        bool large = false;  // %f with it takes a value below 10 (that fits)
        for (char f : std::string(" #+-0"))
          if (!Rand(4)) fmt += f;
        switch (Rand(4)) {
          case 1: fmt += Units(std::to_string(Rand(4) ? Rand(30) : Rand(700))); break;
          case 2: fmt += '*'; push(uint32_t(int32_t(Rand(81)) - 40)); break;
          default: break;
        }
        switch (Rand(5)) {
          case 1: fmt += '.'; break;
          // Large ones up to where the original's 512-byte buffer ends
          // (the native code hands those over).
          case 2:
            large = !Rand(4);
            fmt += u'.' + Units(std::to_string(large ? 400 + Rand(106) : Rand(25)));
            break;
          case 3: fmt += u".*"; push(uint32_t(int32_t(Rand(46)) - 5)); break;
          default: break;
        }
        static const char* const kSizes[] = {"", "", "", "h", "l", "w", "I64", "I", "L", "F", "N"};
        const std::string size = kSizes[Rand(sizeof kSizes / sizeof *kSizes)];
        fmt += Units(size);
        static const char kTypes[] = "cCdiouxXeEfgGnpsSZB";
        const char type = kTypes[Rand(sizeof kTypes - 1)];
        fmt += type;
        if (size == "I") continue;  // 'I' without 64 and what follows are text
        const bool l = size == "l", w = size == "w", h = size == "h";
        switch (type) {
          case 'c':
          case 'C':
            push(Rand(4) ? Rand(0x100) : g_rng());
            break;
          case 'd': case 'i': case 'o': case 'u': case 'x': case 'X': case 'p':
            push(edge());
            if (size == "I64") push(Rand(2) ? 0 : edge());
            break;
          case 'e': case 'E': case 'f': case 'g': case 'G': {
            uint64_t d = Rand(2) ? RandF64() : RandDecimal();
            if (large && type == 'f') {
              double v = (Rand(2) ? 1 : -1) * Rand(100000) / 10000.0;
              std::memcpy(&d, &v, 8);
            }
            push(uint32_t(d));
            push(uint32_t(d >> 32));
            break;
          }
          case 'n':
            push(kCounts + 4 * Rand(64));
            break;
          case 's':
          case 'S': {
            // The narrow engine's %s is wide with l or w, %S unless h; the
            // wide engine (which ignores l) has %s wide unless h, %S with w.
            const bool wide = (type == 'S') != wide_engine ? !h : (wide_engine ? w : l || w);
            push(Rand(8) ? (wide ? wides[Rand(4)] : strings[Rand(4)]) : 0);
            break;
          }
          case 'Z':
            push(Rand(8) ? counted[Rand(4)] : 0);
            break;
          default:
            break;
        }
      }
      for (uint32_t j = 0; j <= fmt.size(); j++) {
        const char16_t u = j < fmt.size() ? fmt[j] : 0;
        if (wide_engine)
          g_mem.write<uint16_t>(kFmt + 2 * j, uint16_t(u));
        else
          g_mem.write<uint8_t>(kFmt + j, uint8_t(u));
      }
      // The stream: a buffer in the data area, its count.
      const uint32_t out = kOut + Rand(0x200);
      // As much as the area holds (sprintf's INT_MAX would run past it), or
      // less, so that output overflows.
      const uint32_t cnt = Rand(4) ? kOutEnd - out : Rand(4) ? Rand(40) : Rand(kOutEnd - out);
      g_mem.write<uint32_t>(kFile, out);
      g_mem.write<uint32_t>(kFile + 4, cnt);
      g_mem.write<uint32_t>(kFile + 8, out);
      g_mem.write<uint32_t>(kFile + 12, Rand(8) ? 0x42 : 0x62);
      Ctx c = Frame({kFile, kFmt, kArgs});
      for (int k = Rand(4) ? Rand(4) : Rand(9); k > 0; k--) recomp::x87::LoadF80(c.fpu, RandF80());
      recomp::x87::SetControlWord(
          c.fpu, Rand(4) ? 0x27F : uint16_t(0x7F | Rand(4) << 8 | Rand(4) << 10));
      c.fpu.sw |= uint16_t(Rand(0x40) & 0x3D);
      std::string shown;
      for (char16_t u : fmt) shown += u < 0x80 ? char(u) : '?';
      Check(name, c, kFpu, std::string(LocaleName(l)) + " " + std::to_string(i) + " \"" + shown + "\"");
    }
  }
  SetLocale(Locale::C);
}

